// Generates the web-server config (security headers + SPA routing) for the chosen
// DEPLOY_TARGET in .env: "apache" -> dist/.htaccess, "netlify" -> dist/_headers + dist/_redirects
import { createHash } from 'node:crypto'
import { createVuetify } from 'vuetify'
import themeOptions from '../src/plugins/themeOptions.js'

// Vuetify injects its theme as an inline <style>; allow exactly that content via its hash
function vuetifyThemeHash() {
  const css = createVuetify({ theme: themeOptions }).theme.styles.value
  return `'sha256-${createHash('sha256').update(css).digest('base64')}'`
}

function buildCsp(env) {
  const connectSrc = ["'self'"]
  if (env.VITE_API_URL) connectSrc.push(new URL(env.VITE_API_URL).origin)

  return [
    "default-src 'self'",
    "script-src 'self'",
    `style-src 'self' ${vuetifyThemeHash()}`,
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src ${connectSrc.join(' ')}`,
    "base-uri 'self'",
    "frame-ancestors 'self'",
    "form-action 'self'",
  ].join('; ')
}

function securityHeaders(env) {
  return {
    'Content-Security-Policy': buildCsp(env),
    'X-Frame-Options': 'DENY',
    'X-Content-Type-Options': 'nosniff',
    'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  }
}

// No <IfModule> guards on purpose: if mod_headers/mod_rewrite are not loaded Apache should
// fail loudly (500) instead of silently serving the site without security headers.
function apacheConfig(headers, base) {
  const lines = Object.entries(headers).map(([name, value]) => `Header always set ${name} "${value}"`)
  return `# Generated by deploy/serverConfig.js (DEPLOY_TARGET=apache) - do not edit by hand
# Requires mod_headers + mod_rewrite and "AllowOverride All" for this folder

DirectoryIndex index.html
Options -Indexes

${lines.join('\n')}
Header always unset X-Powered-By
Header unset X-Powered-By
<FilesMatch "^index\\.html$">
  Header set Cache-Control "no-store"
</FilesMatch>

RewriteEngine On
RewriteBase ${base}
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^ index.html [L]
`
}

function netlifyConfig(headers) {
  const lines = Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)
  return {
    _headers: `/*\n${lines.join('\n')}\n/index.html\n  Cache-Control: no-store\n`,
    _redirects: '/*    /index.html   200\n',
  }
}

export default function serverConfig(env) {
  const target = (env.DEPLOY_TARGET || 'apache').toLowerCase()

  let base = '/'

  return {
    name: 'server-config',
    apply: 'build',
    configResolved(config) {
      base = config.base
    },
    generateBundle() {
      const headers = securityHeaders(env)
      const files = target === 'netlify'
        ? netlifyConfig(headers)
        : target === 'apache'
          ? { '.htaccess': apacheConfig(headers, base) }
          : this.error(`Unknown DEPLOY_TARGET "${target}" (use "apache" or "netlify")`)

      for (const [fileName, source] of Object.entries(files)) {
        this.emitFile({ type: 'asset', fileName, source })
      }
    },
  }
}
